import { expect, test } from '@playwright/test'
import { mockOwnerSignIn, sampleCards, sampleTopics, topicId } from './mock-owner'
import { mockTrainingApi } from './mock-training'

test('spaced: выбор режима, подсказки, самооценка и сохранённый результат', async ({ page }) => {
  const directWrites: string[] = []
  page.on('request', request => {
    if (request.url().includes('/rest/v1/') && !request.url().includes('/rpc/') && request.method() !== 'GET')
      directWrites.push(request.url())
  })
  await mockOwnerSignIn(page, { topics: sampleTopics, cards: sampleCards })
  const server = await mockTrainingApi(page)
  await page.goto('/#training')
  await expect(page.getByRole('heading', { name: 'Начать тренировку' })).toBeVisible()
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await expect(page).toHaveURL(new RegExp(`#training\\?topic=${topicId}&mode=spaced$`))
  await expect(page.getByRole('heading', { name: 'Что такое unknown?' })).toBeVisible()
  await expect(page.getByText('Просмотрено: 1')).toBeVisible()
  await expect(page.getByText('Оценено: 0 / 1')).toBeVisible()
  await expect(page.getByText('Сравните с any.')).toBeVisible()
  await expect(page.locator('.training-question-code')).toContainText('typeof value')
  await page.getByRole('button', { name: 'Подсказка 1' }).click()
  await expect(page.getByText('Нужна проверка типа.')).toBeVisible()
  await page.getByRole('button', { name: 'Подсказка 2' }).click()
  await expect(page.getByText('Используйте typeof.')).toBeVisible()
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await expect(page.getByText('Тип с обязательным сужением.')).toBeVisible()
  await page.getByRole('button', { name: 'Знал', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()
  expect(server.history).toHaveLength(1)
  expect(server.history[0]?.correct).toBe(true)
  expect(server.progress.get(sampleCards[0]!.id)?.correct).toBe(1)
  expect(directWrites).toEqual([])
  await page.getByRole('link', { name: 'К выбору раздела' }).last().click()
  await expect(page.getByRole('heading', { name: 'Разработка.' })).toBeVisible()
  await page.goto('/#dashboard')
  await expect(page.locator('.db-review-count strong')).toHaveText('0')
  await page.goto('/#statistics')
  await expect(page.locator('.metric').filter({ hasText: 'Новые' }).locator('.metric-value')).toHaveText('0')
  await expect(page.locator('.metric').filter({ hasText: 'Изучаются' }).locator('.metric-value')).toHaveText('1')
  await expect(page.locator('.metric').filter({ hasText: 'Всего ответов' }).locator('.metric-value')).toHaveText('1')
  await expect(page.locator('.metric').filter({ hasText: 'Процент правильных ответов' }).locator('.metric-value')).toHaveText('100%')
})

test('активная сессия и выданная попытка восстанавливаются после перезагрузки', async ({ page }) => {
  await mockOwnerSignIn(page, { topics: sampleTopics, cards: sampleCards })
  const server = await mockTrainingApi(page)
  await page.goto(`/#training?topic=${topicId}&mode=spaced`)
  const firstId = await page.locator('.training-card').getAttribute('data-attempt-id')
  await page.reload()
  await expect(page.locator('.training-card')).toHaveAttribute('data-attempt-id', firstId!)
  expect(server.sessions).toHaveLength(1)
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await page.getByRole('button', { name: 'Не знал' }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()
  expect(server.history).toHaveLength(1)
})

test('потерянный ответ сервера повторяется с тем же событием и не удваивает счётчики', async ({ page }) => {
  await mockOwnerSignIn(page, { topics: sampleTopics, cards: sampleCards })
  const server = await mockTrainingApi(page)
  await page.goto(`/#training?topic=${topicId}&mode=spaced`)
  await expect(page.locator('.training-card')).toBeVisible()
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  server.loseNextAnswerResponse()
  await page.getByRole('button', { name: 'Знал', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Не удалось сохранить ответ')
  expect(server.history).toHaveLength(1)
  await page.getByRole('button', { name: 'Повторить' }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()
  expect(server.history).toHaveLength(1)
})

test('infinite не повторяет карточку сразу; mistakes использует сохранённую ошибку', async ({ page }) => {
  const second = { ...sampleCards[0]!, id: '33000000-0000-4000-8000-000000000002', question: 'Второй вопрос?' }
  const cards = [sampleCards[0]!, second]
  await mockOwnerSignIn(page, { topics: sampleTopics, cards })
  const server = await mockTrainingApi(page, cards)
  await page.goto(`/#training?topic=${topicId}&mode=spaced`)
  await expect(page.locator('.training-card')).toBeVisible()
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await page.getByRole('button', { name: 'Не знал' }).click()
  await expect(page.getByRole('heading', { name: 'Второй вопрос?' })).toBeVisible()
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await page.getByRole('button', { name: 'Знал', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()

  await page.goto(`/#training?topic=${topicId}&mode=mistakes`)
  await expect(page.getByRole('heading', { name: 'Что такое unknown?' })).toBeVisible()
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await page.getByRole('button', { name: 'Не знал' }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()
  expect(server.progress.get(sampleCards[0]!.id)?.incorrect).toBe(1)

  await page.goto(`/#training?topic=${topicId}&mode=infinite`)
  const first = await page.locator('.training-card').getAttribute('data-attempt-id')
  await page.getByRole('button', { name: 'Показать ответ' }).click()
  await page.getByRole('button', { name: 'Знал', exact: true }).click()
  await expect(page.locator('.training-card')).not.toHaveAttribute('data-attempt-id', first!)
  await expect(page.getByRole('heading', { name: 'Второй вопрос?' })).toBeVisible()
  await page.getByRole('button', { name: 'Завершить' }).click()
  await expect(page.getByRole('heading', { name: 'Тренировка завершена' })).toBeVisible()
})

test('пустая тема и отсутствие доступных карточек показывают понятное сообщение', async ({ page }) => {
  await mockOwnerSignIn(page, { topics: sampleTopics, cards: [] })
  const server = await mockTrainingApi(page, [])
  await page.goto(`/#training?topic=${topicId}&mode=spaced`)
  await expect(page.getByRole('heading', { name: 'Нет доступных карточек' })).toBeVisible()
  await expect(page.locator('.training-card')).toHaveCount(0)
  await page.goto(`/#training?topic=${topicId}&mode=infinite`)
  await expect(page.getByRole('heading', { name: 'Нет доступных карточек' })).toBeVisible()
  expect(server.sessions.every(session => session.status === 'completed')).toBe(true)
})

test('отмена закрывает сессию, следующий запуск создаёт новую', async ({ page }) => {
  await mockOwnerSignIn(page, { topics: sampleTopics, cards: sampleCards })
  const server = await mockTrainingApi(page)
  await page.goto(`/#training?topic=${topicId}&mode=infinite`)
  await expect(page.locator('.training-card')).toBeVisible()
  await page.getByRole('button', { name: 'Отменить' }).click()
  await expect(page.getByRole('heading', { name: /Что повторить сегодня/ })).toBeVisible()
  expect(server.sessions[0]?.status).toBe('abandoned')
  await page.goto(`/#training?topic=${topicId}&mode=infinite`)
  await expect(page.locator('.training-card')).toBeVisible()
  expect(server.sessions).toHaveLength(2)
})
